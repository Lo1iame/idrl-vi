import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('table supports pagination, page size and filter resets', async ({ page }) => {
  await page.goto('/#components')
  const specimen = page.getByRole('region', { name: '数据表格示例', exact: true })
  await expect(specimen.getByRole('row')).toHaveCount(6)
  await specimen.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(specimen.getByText('RUN-006', { exact: true })).toBeVisible()
  await expect(specimen.getByRole('row')).toHaveCount(3)
  await specimen.getByLabel('筛选示例方法').selectOption('Robust')
  await expect(specimen.getByText('第 1 / 1 页')).toBeVisible()
  await expect(specimen.getByRole('row')).toHaveCount(4)
  await specimen.getByLabel('筛选示例方法').selectOption('all')
  await specimen.getByLabel('每页', { exact: true }).selectOption('10')
  await expect(specimen.getByRole('row')).toHaveCount(8)
  await specimen.getByLabel('搜索表格示例').fill('unmatched')
  await expect(specimen.getByRole('heading', { name: '没有匹配的记录' })).toBeVisible()
  await expect(specimen.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await specimen.getByRole('button', { name: '重置筛选' }).click()
  await expect(specimen.getByRole('row')).toHaveCount(8)
})

test('numeric sorting uses numbers and keeps missing scores last in both directions', async ({ page }) => {
  await page.goto('/#components')
  const specimen = page.getByRole('region', { name: '数据表格示例', exact: true })
  await specimen.getByLabel('每页', { exact: true }).selectOption('10')
  const sort = specimen.getByRole('button', { name: '得分', exact: true })
  await sort.focus()
  await page.keyboard.press('Enter')
  await expect(specimen.getByRole('columnheader', { name: '得分' })).toHaveAttribute('aria-sort', 'ascending')
  await expect(specimen.locator('tbody tr').first()).toContainText('RUN-006')
  await expect(specimen.locator('tbody tr').last()).toContainText('待测量')
  await page.keyboard.press('Enter')
  await expect(specimen.getByRole('columnheader', { name: '得分' })).toHaveAttribute('aria-sort', 'descending')
  await expect(specimen.locator('tbody tr').first()).toContainText('RUN-007')
  await expect(specimen.locator('tbody tr').last()).toContainText('待测量')
})

test('workspace additions reset pagination and export includes all filtered pages', async ({ page }) => {
  await page.goto('/#workspace')
  await page.getByRole('button', { name: '新建演示实验' }).click()
  await page.getByLabel('实验名称', { exact: true }).fill('New pagination record')
  await page.getByRole('button', { name: '添加演示记录' }).click()
  await expect(page.getByText('第 1 / 2 页')).toBeVisible()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('row')).toHaveCount(2)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 JSON' }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  let json = ''
  for await (const chunk of stream!) json += chunk.toString()
  expect(JSON.parse(json)).toHaveLength(6)
  await page.getByLabel('搜索实验').fill('New pagination')
  await expect(page.getByText('第 1 / 1 页')).toBeVisible()
  await expect(page.getByRole('row')).toHaveCount(2)
})

for (const theme of ['light', 'dark']) test(`table is accessible and contained on mobile in ${theme}`, async ({ page }) => {
  await page.addInitScript(value => localStorage.setItem('idrl-theme', value), theme)
  await page.goto('/#components')
  const specimen = page.getByRole('region', { name: '数据表格示例', exact: true })
  await specimen.scrollIntoViewIfNeeded()
  expect((await new AxeBuilder({ page }).include('.data-specimen').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await specimen.screenshot({ path: `output/ui/data-table-${theme}-desktop.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await specimen.screenshot({ path: `output/ui/data-table-${theme}-mobile.png` })
  await page.getByRole('button', { name: '切换语言' }).click()
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByText('Page 2 of 2')).toBeVisible()
})
