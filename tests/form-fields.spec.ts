import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('shared fields associate help and errors while choices update and reset the preview', async ({ page }) => {
  await page.goto('/#components')
  const form = page.getByRole('region', { name: '表单组件示例', exact: true })
  const description = form.getByLabel('实验说明', { exact: false })
  await form.getByRole('button', { name: '保存预览配置' }).click()
  await expect(form.getByLabel('实验名称', { exact: false })).toBeFocused()
  await expect(description).toHaveAttribute('aria-invalid', 'true')
  await expect(description).toHaveAccessibleDescription(/必填.*请输入实验说明/)
  await form.getByLabel('实验名称', { exact: false }).fill('Form reuse')
  await description.fill('First line\nSecond line')
  await form.getByRole('button', { name: '保存预览配置' }).click()
  await expect(description).toHaveAttribute('aria-invalid', 'false')
  await expect(description).toHaveAccessibleDescription(/22 \/ 160/)
  await expect(form.locator('.form-summary').getByText('First line\nSecond line', { exact: true })).toBeVisible()
  const seed = form.getByRole('checkbox', { name: '包含随机种子', exact: true })
  await seed.focus()
  await page.keyboard.press('Space')
  await expect(seed).not.toBeChecked()
  await expect(form.getByText('示例随机种子：42')).toHaveCount(0)
  const notes = form.getByRole('switch', { name: '附带方法说明', exact: true })
  await notes.focus()
  await page.keyboard.press('Space')
  await expect(notes).toHaveAttribute('aria-checked', 'true')
  await expect(form.getByText('方法说明：比较不同设置下的鲁棒表现。')).toBeVisible()
  await expect(form.getByRole('checkbox', { name: '团队同步', exact: true })).toBeDisabled()
  await form.getByRole('button', { name: '重置', exact: true }).click()
  await expect(description).toHaveValue('')
  await expect(description).toHaveAttribute('aria-invalid', 'false')
  await expect(seed).toBeChecked()
  await expect(notes).toHaveAttribute('aria-checked', 'false')
})

test('workspace shared fields preserve native numeric validation and accessible names', async ({ page }) => {
  await page.goto('/#workspace')
  await page.getByRole('button', { name: '新建演示实验' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('实验名称', { exact: false }).fill('Numeric validation')
  const seed = dialog.getByLabel('随机种子', { exact: false })
  await expect(seed).toHaveAccessibleDescription('0–999999 之间的整数。')
  await seed.fill('-1')
  await dialog.getByRole('button', { name: '添加演示记录' }).click()
  await expect(dialog).toBeVisible()
  await expect(seed).toBeFocused()
  await seed.fill('17')
  await dialog.getByRole('button', { name: '添加演示记录' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Numeric validation', exact: true })).toBeVisible()
})

for (const theme of ['light', 'dark']) test(`form fields are accessible and responsive in ${theme}`, async ({ page }) => {
  await page.addInitScript(value => localStorage.setItem('idrl-theme', value), theme)
  await page.goto('/#components')
  const form = page.getByRole('region', { name: '表单组件示例', exact: true })
  await form.scrollIntoViewIfNeeded()
  const description = form.getByLabel('实验说明', { exact: false })
  await description.fill('A'.repeat(200))
  await expect(description).toHaveValue('A'.repeat(160))
  await form.getByRole('button', { name: '保存预览配置' }).click()
  expect((await new AxeBuilder({ page }).include('.specimen-form').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await form.getByRole('button', { name: '重置', exact: true }).click()
  await form.screenshot({ path: `output/ui/form-fields-${theme}-desktop.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await form.screenshot({ path: `output/ui/form-fields-${theme}-mobile.png` })
  await page.getByRole('button', { name: '切换语言' }).click()
  await expect(page.getByRole('checkbox', { name: 'Include random seed', exact: true })).toBeChecked()
  await expect(page.getByLabel('Experiment description', { exact: false })).toHaveAccessibleDescription(/Required/)
})
